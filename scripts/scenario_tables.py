#!/usr/bin/env python3
"""Writes the "The data at a glance" tables into each scenario's README.md.

Usage:
    python scripts/scenario_tables.py scenarios/          # update every scenario README
    python scripts/scenario_tables.py scenarios/ --check  # only report READMEs that are out of date

The tables are built from questions.json and responses.jsonl, so edit those files and run this
script again; do not edit the tables by hand. The tables sit between the two marker comments
below, and everything else in the README is left alone.
"""
import html
import json
import os
import sys

START = "<!-- data-table:start (generated by scripts/scenario_tables.py, do not edit by hand) -->"
END = "<!-- data-table:end -->"


def cell(text):
    t = html.escape(str(text), quote=False).replace("|", "&#124;")
    lines = t.split("\n")
    lines = ["&nbsp;" * (len(l) - len(l.lstrip(" "))) + l.lstrip(" ") for l in lines]
    return "<br>".join(lines)


def build(folder):
    with open(os.path.join(folder, "questions.json"), encoding="utf-8") as f:
        questions = json.load(f)["questions"]
    with open(os.path.join(folder, "responses.jsonl"), encoding="utf-8") as f:
        responses = [json.loads(l) for l in f if l.strip()]

    out = [START, "", "## The data at a glance", "",
           "The scenario as it looks in a Google Sheet when the responses are loaded: one row per student, one column per question. "
           "This is the same layout as the CSV export. You can select the table and paste it into a Google Sheet; if the paste does not come out right, use the CSV export instead. The data itself is in `responses.jsonl`.", ""]
    out.append("| " + " | ".join(["Timestamp", "Email", "Name"] + [cell(q["header"]) for q in questions]) + " |")
    out.append("|" + "---|" * (3 + len(questions)))
    for r in responses:
        row = [cell(r["timestamp"]), cell(r["email"]), cell(r["name"])]
        row += [cell(r["answers"].get(q["id"], "")) for q in questions]
        out.append("| " + " | ".join(row) + " |")
    out += ["", END]
    return "\n".join(out) + "\n"


def update(folder, check=False):
    path = os.path.join(folder, "README.md")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    block = build(folder)
    if START in text and END in text:
        a = text.index(START)
        b = text.index(END) + len(END)
        new = text[:a] + block.rstrip("\n") + text[b:]
    else:
        marker = "## Known relations"
        if marker not in text:
            raise SystemExit("%s: no '## Known relations' heading to insert before" % path)
        i = text.index(marker)
        new = text[:i] + block + "\n" + text[i:]
    if new == text:
        return True
    if check:
        print("out of date:", path)
        return False
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print("updated", path)
    return True


def main(argv):
    args = [a for a in argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__)
        return 2
    root = args[0]
    ok = True
    for d in sorted(os.listdir(root)):
        folder = os.path.join(root, d)
        if os.path.exists(os.path.join(folder, "responses.jsonl")):
            ok = update(folder, "--check" in argv) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
